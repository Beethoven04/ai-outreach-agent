// ---- NODE: Due follow-ups ----
// @node fu_select
const FOLLOWUP_SYSTEM = __FOLLOWUP_SYSTEM__;
const T = tablesFrom($('Read Sheet').first().json);
const M = T.Messages, C = T.Contacts, P = T.Profile, cfg = configOf(T.Config);
if (!cfg.bool('FOLLOWUPS_ENABLED', true)) return [];
const n = now();
const MAX = cfg.num('MAX_FOLLOWUPS', 2);
const facts = P.rows.filter(f => str(f.fact).trim()).map(f => `${f.fact_id}: ${f.fact}`);
const out = [];
for (const c of C.rows) {
  if ((str(c.contact_status) || 'active') !== 'active') continue;
  const mine = M.rows.filter(m => str(m.contact_id) === str(c.contact_id));
  if (mine.some(m => ['', 'draft', 'needs_fix', 'ready', 'sending', 'held'].includes(str(m.status)) && str(m.type) !== 'cold')) continue; // one pending follow-up at a time
  const sent = mine.filter(m => str(m.status) === 'sent' && str(m.sent_at)).sort((a, b) => parseDT(a.sent_at) - parseDT(b.sent_at));
  if (!sent.length) continue;
  if (mine.some(m => ['replied', 'bounced'].includes(str(m.status)))) continue;
  const last = sent[sent.length - 1];
  const fuCount = mine.filter(m => /^fu\d$/.test(str(m.type)) && str(m.status) !== 'cancelled').length;
  if (fuCount >= MAX) continue;
  const due = parseDT(last.followup_due);
  if (!due || due.startOf('day') > n) continue;
  const cold = sent.find(m => (str(m.type) || 'cold') === 'cold') || sent[0];
  const type = `fu${fuCount + 1}`;
  const user = { today: n.toISODate(), followup_type: type, is_final: fuCount + 1 >= MAX,
    recipient: { first_name: c.first_name, role: c.role, company: c.company },
    previous_emails: sent.map(m => ({ type: m.type || 'cold', subject: m.subject, body: m.body, sent_at: m.sent_at })), profile_facts: facts };
  const base = { temperature: 0.3, response_format: { type: 'json_object' }, messages: [{ role: 'system', content: FOLLOWUP_SYSTEM }, { role: 'user', content: JSON.stringify(user) }] };
  out.push({ json: { contact: c, parent: last, cold, type,
    req_primary: { model: cfg.str('LLM_PRIMARY_MODEL', 'gemini-3.5-flash'), ...base },
    req_fallback: { model: cfg.str('LLM_FALLBACK_MODEL', 'openai/gpt-oss-120b'), reasoning_effort: 'low', ...base } } });
  if (out.length >= cfg.num('FOLLOWUP_BATCH', 10)) break;
}
return out;

// ---- NODE: Check primary LLM (follow-ups) ----
// @node fu_check_primary
return $input.all().map((it, i) => {
  const ctx = $('Due follow-ups').itemMatching(i).json;
  let llm = null, llm_error = '';
  try {
    if (it.json.error) throw new Error(JSON.stringify(it.json.error).slice(0, 300));
    llm = parseLLMJson(it.json.choices[0].message.content);
    if (!str(llm.body).trim()) throw new Error('empty body');
  } catch (e) { llm = null; llm_error = e.message; }
  return { json: { ...ctx, llm, llm_ok: !!llm, llm_error, llm_model: ctx.req_primary.model } };
});

// ---- NODE: Create follow-up drafts ----
// @node fu_create
const VIA = '__VIA__';
const T = tablesFrom($('Read Sheet').first().json);
const M = T.Messages;
const W = Writer(), logs = [], notices = [], appendMessages = [];
$input.all().forEach((it, i) => {
  let ctx, llm = null, err = '', model;
  if (VIA === 'primary') { ctx = it.json; llm = ctx.llm; model = ctx.llm_model; }
  else {
    ctx = $('Check primary LLM (follow-ups)').itemMatching(i).json; model = ctx.req_fallback.model;
    try { if (it.json.error) throw new Error(JSON.stringify(it.json.error).slice(0, 300)); llm = parseLLMJson(it.json.choices[0].message.content); if (!str(llm.body).trim()) throw new Error('empty body'); }
    catch (e) { llm = null; err = `primary: ${ctx.llm_error} | fallback: ${e.message}`; }
  }
  const c = ctx.contact, p = ctx.parent;
  if (!llm) { logs.push(logRow('FollowUps', 'error', 'followup_llm_failed', p.msg_id, c.contact_id, err)); notices.push(`⚠️ Could not draft ${ctx.type} for ${c.full_name} (${c.company}): both LLMs failed. Retrying tomorrow.`); return; }
  const id = `${str(ctx.cold.msg_id)}-${ctx.type.toUpperCase()}`;
  appendMessages.push(rowArray(M, {
    msg_id: id, contact_id: c.contact_id, company: c.company, first_name: c.first_name, type: ctx.type, parent_msg_id: p.msg_id,
    subject: 'Re: ' + str(ctx.cold.subject).replace(/^re:\s*/i, ''), body: str(llm.body).trim(), status: 'draft', approved: false,
    gmail_thread_id: p.gmail_thread_id, updated_at: iso(), qc_reasons: `generated by ${model}; waiting for QC`,
  }));
  logs.push(logRow('FollowUps', 'info', 'followup_drafted', id, c.contact_id, str(llm.body)));
});
heartbeat(W, T, 'LAST_RUN_FOLLOWUPS');
return [{ json: { data: W.data, logs, notices, appendMessages } }];
